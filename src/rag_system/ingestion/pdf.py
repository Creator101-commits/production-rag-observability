"""NIST AI RMF corpus acquisition: download, verify, extract, manifest.

Page numbers are 1-based physical PDF page indices everywhere.
Downloads happen on Kaggle; tests exercise extraction and normalization
on locally generated bytes only.
"""

from __future__ import annotations

import hashlib
import io
import json
import re
import unicodedata
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import httpx

from rag_system.ingestion.schema import Document, Page

# Hyphen + line break + lowercase letter is treated as a word broken
# across lines; anything else keeps the hyphen and becomes a space.
_HYPHEN_LINE_BREAK = re.compile(r"([a-z])-[ \t]*\n[ \t]*([a-z])")


@dataclass(frozen=True)
class CorpusDocumentSpec:
    """Pinned source document: identity, URL, and expected integrity values."""

    document_id: str
    title: str
    url: str
    expected_sha256: str
    expected_pages: int | None = None


NIST_CORPUS_SPECS: tuple[CorpusDocumentSpec, ...] = (
    CorpusDocumentSpec(
        document_id="nist_ai_100_1",
        title="Artificial Intelligence Risk Management Framework (AI RMF 1.0)",
        url="https://nvlpubs.nist.gov/nistpubs/ai/NIST.AI.100-1.pdf",
        expected_sha256=(
            "7576edb531d9848825814ee88e28b1795d3a84b435b4b797d3670eafdc4a89f1"
        ),
        expected_pages=48,
    ),
    CorpusDocumentSpec(
        document_id="nist_ai_600_1",
        title="Artificial Intelligence Risk Management Framework: Generative AI Profile",
        url="https://nvlpubs.nist.gov/nistpubs/ai/NIST.AI.600-1.pdf",
        expected_sha256=(
            "6e73620ab6b64e90ef2c04bf0e0d6246185a2f4b1b13cab0df494496cff89b6a"
        ),
        expected_pages=64,
    ),
)


@dataclass(frozen=True)
class PageExtraction:
    """One physical PDF page: normalized text plus extraction diagnostics."""

    page_number: int
    text: str
    raw_char_count: int
    extraction_failed: bool


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def normalize_pdf_text(text: str) -> str:
    """NFKC, full whitespace collapse, and conservative dehyphenation."""
    rejoined = _HYPHEN_LINE_BREAK.sub(r"\1\2", text)
    collapsed = re.sub(r"\s+", " ", unicodedata.normalize("NFKC", rejoined))
    return collapsed.strip()


def download_pdf(spec: CorpusDocumentSpec, dest_dir: Path) -> Path:
    """Download a pinned PDF and verify its SHA-256 before returning."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / f"{spec.document_id}.pdf"
    if dest.exists() and sha256_bytes(dest.read_bytes()) == spec.expected_sha256:
        return dest
    with httpx.stream("GET", spec.url, follow_redirects=True, timeout=120.0) as resp:
        resp.raise_for_status()
        chunks: list[bytes] = []
        for chunk in resp.iter_bytes():
            chunks.append(chunk)
    data = b"".join(chunks)
    digest = sha256_bytes(data)
    if digest != spec.expected_sha256:
        raise ValueError(
            f"{spec.document_id}: sha256 mismatch: expected "
            f"{spec.expected_sha256}, got {digest}"
        )
    dest.write_bytes(data)
    return dest


def extract_pdf_pages(pdf_bytes: bytes) -> list[PageExtraction]:
    """Extract per-page text with pypdf; flag pages with no text layer."""
    import pypdf  # noqa: PLC0415 - keep core import graph light

    reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
    pages: list[PageExtraction] = []
    for index, page in enumerate(reader.pages, start=1):
        try:
            raw = page.extract_text() or ""
        except Exception:
            raw = ""
        pages.append(
            PageExtraction(
                page_number=index,
                text=normalize_pdf_text(raw),
                raw_char_count=len(raw),
                extraction_failed=len(raw.strip()) == 0,
            )
        )
    return pages


def ingest_document(
    spec: CorpusDocumentSpec, pdf_path: Path
) -> tuple[Document, dict[str, Any]]:
    """Verify integrity, extract pages, and build a provenance Document."""
    pdf_bytes = pdf_path.read_bytes()
    digest = sha256_bytes(pdf_bytes)
    if digest != spec.expected_sha256:
        raise ValueError(
            f"{spec.document_id}: sha256 mismatch: expected "
            f"{spec.expected_sha256}, got {digest}"
        )
    import pypdf  # noqa: PLC0415

    parser_version = pypdf.__version__
    extractions = extract_pdf_pages(pdf_bytes)
    if spec.expected_pages is not None and len(extractions) != spec.expected_pages:
        raise ValueError(
            f"{spec.document_id}: expected {spec.expected_pages} pages, "
            f"got {len(extractions)}"
        )
    failed = [p.page_number for p in extractions if p.extraction_failed]
    doc = Document(
        document_id=spec.document_id,
        title=spec.title,
        source_url=spec.url,
        version=f"sha256:{digest[:12]}",
        pages=[Page(page_number=p.page_number, text=p.text) for p in extractions],
        source_sha256=digest,
    )
    manifest: dict[str, Any] = {
        "document_id": spec.document_id,
        "title": spec.title,
        "source_url": spec.url,
        "sha256": digest,
        "byte_size": len(pdf_bytes),
        "page_count": len(extractions),
        "failed_pages": failed,
        "parser_version": parser_version,
    }
    return doc, manifest


def ingest_corpus(
    specs: tuple[CorpusDocumentSpec, ...] | list[CorpusDocumentSpec],
    raw_dir: Path,
    *,
    download: bool = True,
) -> tuple[list[Document], dict[str, Any]]:
    """Ingest all pinned documents and return docs plus a corpus manifest."""
    documents: list[Document] = []
    entries: list[dict[str, Any]] = []
    for spec in specs:
        pdf_path = (
            download_pdf(spec, raw_dir / spec.document_id)
            if download
            else raw_dir / spec.document_id / f"{spec.document_id}.pdf"
        )
        doc, manifest = ingest_document(spec, pdf_path)
        documents.append(doc)
        entries.append(manifest)
    corpus_manifest: dict[str, Any] = {
        "generated_at": datetime.now(UTC).isoformat(),
        "documents": entries,
    }
    return documents, corpus_manifest


def write_manifest(manifest: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
